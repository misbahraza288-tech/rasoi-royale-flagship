#!/usr/bin/env python3
# Screenshots (390x844, 2x) and the order-flow recording for the demo.
# Usage: python3 tests/screens.py http://host/ /out/dir
# Sets the browser clock to a daytime IST moment so the branch shows open.
import sys, os, datetime, glob, shutil
from playwright.sync_api import sync_playwright, expect
BASE = sys.argv[1].rstrip('/') + '/'
OUT = sys.argv[2]
os.makedirs(OUT, exist_ok=True)
FIXED = datetime.datetime(2026, 11, 5, 13, 10, 0)  # local clock; IST offset is applied by the page's Intl (Asia/Kolkata) from UTC
FIXED_UTC = datetime.datetime(2026, 11, 5, 7, 40, 0, tzinfo=datetime.timezone.utc)
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True, record_video_dir=OUT + '/video', record_video_size={'width': 390, 'height': 844})
    ctx.clock.set_fixed_time(FIXED_UTC)
    cust = ctx.new_page()
    cust.goto(BASE, wait_until='networkidle')
    cust.wait_for_timeout(700)
    cust.screenshot(path=OUT + '/flagship-01.jpg', type='jpeg', quality=84)
    cust.click('.bottomnav button[data-tab="menu"]'); cust.wait_for_timeout(400)
    cust.screenshot(path=OUT + '/flagship-02.jpg', type='jpeg', quality=84)
    cust.locator('.item .itemtap').filter(has_text='Chicken Dum Biryani').first.click(); cust.wait_for_timeout(500)
    cust.locator('.sheet input[value="Extra raita"]').check()
    cust.screenshot(path=OUT + '/flagship-03.jpg', type='jpeg', quality=84)
    cust.click('.sheet button[data-act="addsheet"]'); cust.wait_for_timeout(300)
    cust.locator('.item .itemtap').filter(has_text='Butter Naan').first.click(); cust.wait_for_timeout(300)
    cust.click('.sheet button[data-act="addsheet"]'); cust.wait_for_timeout(300)
    cust.click('.bottomnav button[data-tab="cart"]'); cust.wait_for_timeout(300)
    cust.fill('#coupon', 'ROYAL10'); cust.click('button[data-act="applycoupon"]')
    cust.fill('#cname', 'Demo Customer'); cust.fill('#cphone', '9000012345'); cust.fill('#addr', 'Demo address, Bank More, Dhanbad'); cust.locator('#cphone').blur()
    cust.wait_for_timeout(300)
    cust.screenshot(path=OUT + '/flagship-04.jpg', type='jpeg', quality=84)
    cust.wait_for_timeout(600)
    cust.click('button[data-act="place"]'); cust.wait_for_timeout(900)
    code = cust.locator('.tracker .code').inner_text()
    cust.screenshot(path=OUT + '/flagship-05.jpg', type='jpeg', quality=84)
    adm = ctx.new_page()
    adm.goto(BASE + 'admin/', wait_until='networkidle')
    adm.wait_for_timeout(400)
    adm.fill('#pin', '4321'); adm.wait_for_timeout(300); adm.click('#loginform button')
    adm.click('[data-nav="orders"]'); expect(adm.locator('.ticket', has_text=code)).to_be_visible(timeout=8000)
    adm.wait_for_timeout(900)
    adm.screenshot(path=OUT + '/flagship-06.jpg', type='jpeg', quality=84)
    adm.locator('.ticket', has_text=code).locator('button[data-to="accepted"]').click(); cust.wait_for_timeout(900)
    adm.locator('.ticket', has_text=code).locator('button[data-to="cooking"]').click(); cust.wait_for_timeout(1200)
    cust.bring_to_front(); cust.wait_for_timeout(600)
    cust.screenshot(path=OUT + '/flagship-05b-cooking.jpg', type='jpeg', quality=84)
    adm.bring_to_front()
    adm.click('[data-nav="menu"]'); adm.wait_for_timeout(500)
    adm.screenshot(path=OUT + '/flagship-07.jpg', type='jpeg', quality=84)
    adm.click('[data-nav="integrations"]'); adm.wait_for_timeout(400)
    adm.screenshot(path=OUT + '/flagship-08.jpg', type='jpeg', quality=84)
    adm.click('[data-nav="dashboard"]'); adm.wait_for_timeout(400)
    adm.screenshot(path=OUT + '/flagship-09.jpg', type='jpeg', quality=84)
    adm.click('[data-nav="orders"]'); adm.wait_for_timeout(300)
    adm.locator('.ticket', has_text=code).locator('button[data-to="ready"]').click(); cust.wait_for_timeout(900)
    adm.locator('.ticket', has_text=code).locator('button[data-to="out"]').click(); cust.wait_for_timeout(1500)
    cust.bring_to_front(); cust.wait_for_timeout(800)
    print('code', code)
    cust.close(); adm.close()
    ctx.close(); b.close()
videos = sorted(glob.glob(OUT + '/video/*.webm'))
print('videos', videos)
